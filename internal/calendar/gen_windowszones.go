//go:build ignore

// gen_windowszones downloads CLDR's windowsZones.xml at a pinned release and
// writes windowszones.go: Windows time zone name → primary IANA zone
// (territory "001"). Run with: go generate ./internal/calendar
package main

import (
	"bytes"
	"encoding/xml"
	"fmt"
	"go/format"
	"io"
	"log"
	"net/http"
	"os"
	"sort"
	"time"
)

const cldrRelease = "release-48"

const source = "https://raw.githubusercontent.com/unicode-org/cldr/" + cldrRelease + "/common/supplemental/windowsZones.xml"

type supplemental struct {
	MapZones []struct {
		Other     string `xml:"other,attr"`
		Territory string `xml:"territory,attr"`
		Type      string `xml:"type,attr"`
	} `xml:"windowsZones>mapTimezones>mapZone"`
}

func main() {
	client := &http.Client{Timeout: 30 * time.Second}
	resp, err := client.Get(source)
	if err != nil {
		log.Fatal(err)
	}
	defer resp.Body.Close()
	if resp.StatusCode != http.StatusOK {
		log.Fatalf("GET %s: %s", source, resp.Status)
	}
	raw, err := io.ReadAll(resp.Body)
	if err != nil {
		log.Fatal(err)
	}

	var doc supplemental
	if err := xml.Unmarshal(raw, &doc); err != nil {
		log.Fatal(err)
	}
	zones := map[string]string{}
	for _, z := range doc.MapZones {
		if z.Territory == "001" {
			zones[z.Other] = z.Type
		}
	}
	if len(zones) < 100 {
		log.Fatalf("only %d zones parsed: unexpected CLDR format", len(zones))
	}
	names := make([]string, 0, len(zones))
	for n := range zones {
		names = append(names, n)
	}
	sort.Strings(names)

	var b bytes.Buffer
	fmt.Fprintf(&b, "// Code generated by gen_windowszones.go from CLDR %s; DO NOT EDIT.\n\n", cldrRelease)
	b.WriteString("package calendar\n\n")
	b.WriteString("// windowsZones maps Windows time zone names (as Microsoft Graph returns in\n")
	b.WriteString("// originalStartTimeZone) to their primary IANA zone (CLDR territory 001).\n")
	b.WriteString("var windowsZones = map[string]string{\n")
	for _, n := range names {
		fmt.Fprintf(&b, "\t%q: %q,\n", n, zones[n])
	}
	b.WriteString("}\n")

	out, err := format.Source(b.Bytes())
	if err != nil {
		log.Fatal(err)
	}
	if err := os.WriteFile("windowszones.go", out, 0o644); err != nil {
		log.Fatal(err)
	}
	fmt.Printf("windowszones.go: %d zones from CLDR %s\n", len(names), cldrRelease)
}
